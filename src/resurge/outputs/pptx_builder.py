@dataclass
class TCell:
    """Table cell content and styling (``sub`` = a smaller muted second line)."""

    text: str = ""
    bold: bool = False
    color: str | None = None
    fill: str | None = None
    align: str = "l"
    sub: str = ""
    swatch: str | None = None
    link: str | None = None
    italic: bool = False


@dataclass
class TableStyle:
    """Column layout and text budgets for a deck table."""

    headers: list[str]
    widths: list[float]
    size: float = 10.5
    sub_size: float = 9.0
    max_lines: int = 2
    sub_lines: int = 2
    header_size: float = 10.5

    @property
    def header_height(self) -> float:
        lines = max(
            len(wrap_lines(h, _cpl(w - 2 * CELL_PAD_X, self.header_size, True)) or [""])
            for h, w in zip(self.headers, self.widths)
        )
        return lines * _line_h(self.header_size) + 2 * CELL_PAD_Y + 0.04


def _auto_widths(rows: Sequence[Sequence[TCell | str]], headers: Sequence[str], total: float,
                 minimum: float = 0.7) -> list[float]:
    """Column widths proportional to (capped) content length, each at least ``minimum``."""
    weights = []
    for j, header in enumerate(headers):
        lengths = sorted(len(one_line(r[j].text if isinstance(r[j], TCell) else r[j])) for r in rows if j < len(r))
        typical = lengths[int(len(lengths) * 0.9)] if lengths else 0
        weights.append(max(len(header), min(40, typical), 4) + 2)
    widths = [total * w / sum(weights) for w in weights]
    short = [j for j, w in enumerate(widths) if w < minimum]
    if short and len(short) < len(widths):
        spare = sum(minimum - widths[j] for j in short)
        rest = sum(widths[j] for j in range(len(widths)) if j not in short)
        widths = [minimum if j in short else w - spare * w / rest for j, w in enumerate(widths)]
    return widths


def _clip_lines(text: str, cpl: int, max_lines: int) -> tuple[str, int]:
    text = one_line(text)
    if not text:
        return "", 0
    lines = wrap_lines(text, cpl)
    if len(lines) <= max_lines:
        return text, len(lines)
    return clip(text, _budget(text, cpl, max_lines)), max_lines


def _layout_row(cells: Sequence[TCell | str], style: TableStyle) -> tuple[list[TCell], float]:
    """Clip every cell to its budget and return the row with its height (inches)."""
    prepared: list[TCell] = []
    height = 0.0
    for raw, width in zip(cells, style.widths):
        cell = raw if isinstance(raw, TCell) else TCell(one_line(raw))
        inner = width - 2 * CELL_PAD_X
        cpl = _cpl(inner, style.size, cell.bold) - (2 if cell.swatch else 0)
        text, n = _clip_lines(cell.text, cpl, style.max_lines)
        sub, m = _clip_lines(cell.sub, _cpl(inner, style.sub_size), style.sub_lines) if cell.sub else ("", 0)
        prepared.append(replace(cell, text=text, sub=sub))
        height = max(height, max(1, n) * _line_h(style.size) + m * _line_h(style.sub_size))
    return prepared, height + 2 * CELL_PAD_Y + 0.02


def _paginate(
    rows: Sequence[Sequence[TCell | str]],
    style: TableStyle,
    avail_h: float,
    max_rows: int | None = None,
    first_avail_h: float | None = None,
) -> list[list[tuple[list[TCell], float]]]:
    """Split rows into pages that fit ``avail_h`` (``first_avail_h`` for page one)."""
    pages: list[list[tuple[list[TCell], float]]] = []
    page: list[tuple[list[TCell], float]] = []
    limit = first_avail_h if first_avail_h is not None else avail_h
    used = style.header_height
    for row in rows:
        prepared, height = _layout_row(row, style)
        if page and (used + height > limit + 1e-6 or (max_rows is not None and len(page) >= max_rows)):
            pages.append(page)
            page, used, limit = [], style.header_height, avail_h
        page.append((prepared, height))
        used += height
    if page:
        pages.append(page)
    return pages


def _fill_cell(cell: Any, tc: TCell, size: float, style: TableStyle, default_fill: str, header: bool = False) -> None:
    cell.margin_left = cell.margin_right = Inches(CELL_PAD_X)
    cell.margin_top = cell.margin_bottom = Inches(CELL_PAD_Y)
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    cell.fill.solid()
    cell.fill.fore_color.rgb = _rgb(tc.fill or default_fill)
    text_frame = cell.text_frame
    text_frame.word_wrap = True
    runs: list[Run] = []
    if tc.swatch:
        runs.append(Run("■ ", color=tc.swatch))
    runs.append(Run(tc.text, bold=tc.bold or header, italic=tc.italic, color=tc.color, link=tc.link))
    paras = [Para(runs, size=size, color=tc.color or (INK if header else SLATE[800]), align=tc.align,
                  space_after=0, max_lines=99)]
    if tc.sub:
        paras.append(Para([Run(tc.sub)], size=style.sub_size, color=SLATE[500], align=tc.align, space_after=0,
                          max_lines=99))
    _write(text_frame, paras)


def _draw_table(slide: Slide, x: float, y: float, style: TableStyle, page: list[tuple[list[TCell], float]]) -> float:
    """Draw one page of a table; returns its height (inches)."""
    heights = [style.header_height] + [h for _, h in page]
    frame = slide.shapes.add_table(
        len(heights), len(style.widths), Inches(x), Inches(y), Inches(sum(style.widths)), Inches(sum(heights))
    )
    table = frame.table
    table.horz_banding = False
    for j, width in enumerate(style.widths):
        table.columns[j].width = Inches(width)
    for i, height in enumerate(heights):
        table.rows[i].height = Inches(height)
    for j, title in enumerate(style.headers):
        _fill_cell(table.cell(0, j), TCell(title, align="l"), style.header_size, style, SLATE[100], header=True)
    for i, (cells, _) in enumerate(page, start=1):
        zebra = WHITE if i % 2 else SLATE[50]
        for j, cell in enumerate(cells):
            _fill_cell(table.cell(i, j), cell, style.size, style, zebra)
    return sum(heights)


