    def risk_matrix(self, slide: Slide, x: float, y: float, cell: float) -> float:
        """Native 5x5 likelihood x impact matrix with risk markers; returns its width."""
        labels = risk_labels(self.r)
        label_w = 0.95
        gx, gy = x + label_w, y + 0.3
        self.text(slide, x, y, label_w + 2.0, 0.28,
                  [para("Impact ↑", size=9, bold=True, color=SLATE[500], max_lines=1, space_after=0)])
        for impact in range(1, 6):
            row_y = gy + (5 - impact) * cell
            self.text(slide, x, row_y, label_w - 0.04, cell,
                      [para(f"{IMPACT_LABELS[impact]} {impact}", size=9, color=SLATE[600], align="r", max_lines=1,
                            space_after=0)], anchor="m")
            for likelihood in range(1, 6):
                score = likelihood * impact
                cx = gx + (likelihood - 1) * cell
                self.box(slide, cx + 0.02, row_y + 0.02, cell - 0.04, cell - 0.04,
                         fill=RISK_BAND_FILL[risk_band(score)])
                self.text(slide, cx + 0.02, row_y + 0.02, 0.45, 0.24,
                          [para(str(score), size=7.5, color=SLATE[600], max_lines=1, space_after=0)])
        for likelihood in range(1, 6):
            self.text(slide, gx + (likelihood - 1) * cell, gy + 5 * cell + 0.02, cell, 0.56, [
                para(str(likelihood), size=9, bold=True, color=SLATE[600], align="c", max_lines=1, space_after=0),
                para(LIKELIHOOD_LABELS[likelihood], size=8, color=SLATE[500], align="c", max_lines=2,
                     space_after=0),
            ])
        self.text(slide, gx, gy + 5 * cell + 0.58, 5 * cell, 0.26,
                  [para("Likelihood →", size=9, bold=True, color=SLATE[500], align="c", max_lines=1,
                        space_after=0)])
        groups: dict[tuple[int, int], list] = {}
        for risk in sorted_risks(self.r):
            key = (clamp_int(risk.likelihood, 1, 5), clamp_int(risk.impact, 1, 5))
            groups.setdefault(key, []).append(risk)
        dot, step = 0.28, 0.27
        for (likelihood, impact), group in groups.items():
            marks = [labels[r.id] for r in group] if len(group) <= 6 else \
                [labels[r.id] for r in group[:5]] + [f"+{len(group) - 5}"]
            cols = min(3, len(marks))
            n_rows = (len(marks) + cols - 1) // cols
            cx = gx + (likelihood - 0.5) * cell
            cy = gy + (5.5 - impact) * cell + 0.04
            for index, mark in enumerate(marks):
                row, col = divmod(index, cols)
                in_row = min(cols, len(marks) - row * cols)
                mx = cx + (col - (in_row - 1) / 2) * step - dot / 2
                my = cy + (row - (n_rows - 1) / 2) * step - dot / 2
                self.badge(slide, mx, my, dot, dot, mark, NAVY, WHITE, size=7.5 if len(mark) <= 3 else 6,
                           oval=True, line=WHITE)
        legend_y = gy + 5 * cell + 0.9
        slot = (label_w + 5 * cell) / 4
        for k, (band, span) in enumerate((("Low", "1–4"), ("Medium", "5–9"), ("High", "10–14"),
                                          ("Critical", "15–25"))):
            lx = x + 0.1 + k * slot
            self.box(slide, lx, legend_y + 0.06, 0.16, 0.16, fill=RISK_BAND_FILL[band])
            self.text(slide, lx + 0.18, legend_y, slot - 0.2, 0.28,
                      [para(f"{band} {span}", size=8.5, color=SLATE[600], max_lines=1, space_after=0)])
        return label_w + 5 * cell

