def _conf_style(confidence: float | None) -> tuple[str, str, str]:
    """(fill, ink, label) for a confidence badge."""
    if confidence is None:
        return SLATE[100], SLATE[600], "n/a"
    if confidence >= 0.8:
        return "#DCFCE7", "#166534", pct(confidence)
    if confidence >= 0.6:
        return "#FEF3C7", "#92400E", pct(confidence)
    return "#FEE2E2", "#991B1B", pct(confidence)


class _Deck:
    """Stateful helper that draws the slides of one report."""

    def __init__(self, report: ResearchReport, charts: Mapping[str, Path | str] | None) -> None:
        self.r = report
        self.charts = {k: Path(v) for k, v in (charts or {}).items() if v and Path(v).is_file()}
        self.facts = fact_index(report)
        self.colors = entity_colors(report)
        self.title = report_title(report)
        self.date = fmt_date(report.created_at)
        self.prs = Presentation()
        self.prs.slide_width = Emu(12192000)
        self.prs.slide_height = Emu(6858000)
        self.layout = self.prs.slide_layouts[6]
        self.dark: set[int] = set()
        self.threat_shown = False
        self.target = display_name(target_name(report))
        self.toc: list[tuple[str, str, int]] = []  # (title, blurb, slide number) for the contents slide
        self.pending: tuple[str, str] | None = None  # section divider to insert before the next content slide
        self.contents_slide: Slide | None = None

    # ---- primitives ------------------------------------------------------ #
    def box(
        self,
        slide: Slide,
        x: float,
        y: float,
        w: float,
        h: float,
        fill: str | None = None,
        line: str | None = None,
        rounded: bool = False,
        oval: bool = False,
    ) -> Any:
        kind = MSO_SHAPE.OVAL if oval else MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE
        shape = slide.shapes.add_shape(kind, Inches(x), Inches(y), Inches(w), Inches(h))
        if fill:
            shape.fill.solid()
            shape.fill.fore_color.rgb = _rgb(fill)
        else:
            shape.fill.background()
        if line:
            shape.line.color.rgb = _rgb(line)
            shape.line.width = Pt(0.75)
        else:
            shape.line.fill.background()
        shape.shadow.inherit = False
        if rounded:
            shape.adjustments[0] = min(0.5, 0.08 / max(0.01, min(w, h)))
        return shape

    def text(
        self, slide: Slide, x: float, y: float, w: float, h: float, paras: Sequence[Para], anchor: str = "t"
    ) -> list[Para]:
        """Fit ``paras`` into a new text box; returns the paragraphs that did not fit."""
        fitted, overflow = fit_paras(paras, w - 2 * PAD_X, h - 2 * PAD_Y)
        if not fitted:
            return list(overflow)
        shape = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        frame = shape.text_frame
        frame.word_wrap = True
        frame.auto_size = MSO_AUTO_SIZE.NONE
        frame.margin_left = frame.margin_right = Inches(PAD_X)
        frame.margin_top = frame.margin_bottom = Inches(PAD_Y)
        frame.vertical_anchor = _ANCHOR[anchor]
        _write(frame, fitted)
        return overflow

    def badge(self, slide: Slide, x: float, y: float, w: float, h: float, label: str, fill: str, ink: str,
              size: float = 11, oval: bool = False, line: str | None = None) -> None:
        shape = self.box(slide, x, y, w, h, fill=fill, rounded=not oval, oval=oval, line=line)
        frame = shape.text_frame
        frame.word_wrap = True
        frame.auto_size = MSO_AUTO_SIZE.NONE
        frame.margin_left = frame.margin_right = frame.margin_top = frame.margin_bottom = Inches(0.02)
        frame.vertical_anchor = MSO_ANCHOR.MIDDLE
        _write(frame, [para(clip(label, _cpl(w - 0.04, size, True)), size=size, bold=True, color=ink, align="c",
                            max_lines=1, space_after=0)])

    def picture(self, slide: Slide, name: str, x: float, y: float, w: float, h: float,
                align: str = "c", valign: str = "t") -> tuple[float, float, float, float] | None:
        """Place a chart scaled to fit the box (aspect preserved); ``None`` if absent."""
        path = self.charts.get(name)
        if path is None:
            return None
        with Image.open(path) as image:
            px_w, px_h = image.size
        ratio = px_w / max(1, px_h)
        iw, ih = (h * ratio, h) if w / h > ratio else (w, w / ratio)
        ix = x + (w - iw) / 2 if align == "c" else x
        if valign == "m":
            y += (h - ih) / 2
        pic = slide.shapes.add_picture(str(path), Inches(ix), Inches(y), Inches(iw), Inches(ih))
        pic._element.nvPicPr.cNvPr.set("descr", CHART_TITLES.get(name, name))
        return ix, y, iw, ih

    def card(
        self,
        slide: Slide,
        x: float,
        y: float,
        w: float,
        h: float,
        title: str,
        accent: str,
        paras: Sequence[Para],
        band: bool = False,
    ) -> list[Para]:
        """Light panel with a thin accent line on top (``band``: the title takes the accent colour too)."""
        self.box(slide, x, y, w, h, fill=PANEL)
        self.box(slide, x, y, w, 0.05, fill=accent)
        self.text(slide, x + 0.1, y + 0.13, w - 0.2, 0.36,
                  [para(title, size=12.5, bold=True, color=accent if band else INK, max_lines=1, space_after=0)],
                  anchor="m")
        body_y = y + 0.56
        body = list(paras) or [para("Nothing reported.", size=10.5, color=SLATE[400], max_lines=1)]
        return self.text(slide, x + 0.12, body_y, w - 0.22, y + h - body_y - 0.08, body)

    def new(self, title: str, kicker: str = "", swatch: str | None = None) -> Slide:
        """Content slide: a short teal mark, the section label, a serif title and a hairline, on white."""
        self._open_section()
        slide = self.prs.slides.add_slide(self.layout)
        self.box(slide, MARGIN, 0.43, 0.34, 0.05, fill=TEAL)
        label_x = MARGIN + 0.46
        if swatch:  # the company's colour, as in the charts
            self.box(slide, label_x, 0.385, 0.14, 0.14, fill=swatch, oval=True)
            label_x += 0.24
        if kicker:
            self.text(slide, label_x - PAD_X, 0.3, SLIDE_W - MARGIN - label_x + PAD_X, 0.3,
                      [para(kicker.upper(), size=9.5, bold=True, color=TEAL_DARK, max_lines=1, space_after=0,
                            tracking=100)], anchor="m")
        self.text(slide, MARGIN - PAD_X, 0.6, CONTENT_W + 2 * PAD_X, 0.56,
                  [para(title, size=24, color=INK, serif=True, max_lines=1, space_after=0)], anchor="m")
        self.box(slide, MARGIN, HEADER_RULE_Y, CONTENT_W, 0.012, fill=HAIR)
        return slide

    def dark_slide(self) -> Slide:
        slide = self.prs.slides.add_slide(self.layout)
        self.dark.add(len(self.prs.slides))
        self.box(slide, 0, 0, SLIDE_W, SLIDE_H, fill=NAVY)
        return slide

    def section(self, title: str, blurb: str) -> None:
        """Start a section: its divider slide appears only if the section produces a slide."""
        self.pending = (title, blurb)

    def _open_section(self) -> None:
        if not self.pending:
            return
        title, blurb = self.pending
        self.pending = None
        slide = self.dark_slide()
        number = len(self.toc) + 1
        self.toc.append((title, blurb, len(self.prs.slides)))
        x = MARGIN + 0.35
        self.text(slide, x - PAD_X, 1.75, 4.0, 1.3,
                  [para(f"{number:02d}", size=72, serif=True, color=TEAL, max_lines=1, space_after=0)])
        self.box(slide, x, 3.2, 0.7, 0.06, fill=TEAL)
        self.text(slide, x - PAD_X, 3.4, CONTENT_W - 0.6, 0.95,
                  [para(title, size=42, serif=True, color=WHITE, max_lines=1, space_after=0)])
        self.text(slide, x - PAD_X, 4.4, 9.0, 0.95,
                  [para(blurb, size=16, color=SLATE[300], max_lines=2, space_after=0)])

    def contents(self) -> None:
        """The contents slide; its rows are written once every slide exists (see ``fill_contents``)."""
        self.contents_slide = self.new("What's inside", "Contents")

    def fill_contents(self) -> None:
        slide, rows = self.contents_slide, self.toc
        if slide is None or not rows:
            return
        row_h = min(0.86, CONTENT_H / len(rows))
        for k, (title, blurb, page) in enumerate(rows):
            y = TOP + k * row_h
            if k:
                self.box(slide, MARGIN, y - 0.02, CONTENT_W, 0.01, fill=HAIR)
            self.text(slide, MARGIN - PAD_X, y + 0.06, 0.9, 0.5,
                      [para(f"{k + 1:02d}", size=20, serif=True, color=TEAL_DARK, max_lines=1, space_after=0)])
            self.text(slide, MARGIN + 0.85, y + 0.04, 9.6, row_h - 0.08, [
                para(title, size=17, serif=True, color=INK, max_lines=1, space_after=1),
                para(blurb, size=10.5, color=SLATE[500], max_lines=1, space_after=0),
            ])
            self.text(slide, SLIDE_W - MARGIN - 1.2, y + 0.06, 1.2 + PAD_X, 0.5,
                      [para(str(page), size=16, serif=True, color=INK, align="r", max_lines=1, space_after=0)])

    def notes(self, slide: Slide, fact_ids: Iterable[str], intro: str = "") -> None:
        """Speaker notes listing the facts (claim, status, URLs) behind a slide."""
        ids = list(dict.fromkeys(i for i in fact_ids if i))
        lines = [intro] if intro else []
        if ids:
            lines.append(f"Evidence for this slide ({len(ids)} fact{'s' if len(ids) != 1 else ''}):")
            for fid in ids[:60]:
                fact = self.facts.get(fid)
                if fact is None:
                    lines.append(f"• {fid}: not in the fact base")
                    continue
                lines.append(f"• {fid} [{fact.status}, {pct(fact.confidence)} confidence] {clip(fact.claim, 220)}")
                lines += [f"    {url}" for url in (safe_url(u) for u in fact.source_urls[:4]) if url]
            if len(ids) > 60:
                lines.append(f"… and {len(ids) - 60} more fact IDs (see the Evidence section of the full report).")
        if lines:
            slide.notes_slide.notes_text_frame.text = "\n".join(flatten(line) for line in lines)

    def insight_paras(self, items: Sequence[Insight], size: float = 11.0, max_lines: int = 2,
                      bullet_color: str = SLATE[400]) -> list[Para]:
        out = []
        for item in items:
            runs = [Run("Inferred · ", italic=True, color=SLATE[500])] if item.inferred else []
            runs.append(Run(one_line(item.text)))
            out.append(Para(runs, size=size, color=SLATE[800], bullet="•", bullet_color=bullet_color,
                            max_lines=max_lines, space_after=5))
        return out

    def bullet_paras(self, items: Iterable[str], size: float = 11.0, max_lines: int = 2,
                     bullet_color: str = SLATE[400]) -> list[Para]:
        return [
            para(item, size=size, color=SLATE[800], bullet="•", bullet_color=bullet_color, max_lines=max_lines,
                 space_after=5)
            for item in items
            if one_line(item)
        ]

