@dataclass
class Run:
    """A styled span of text."""

    text: str
    bold: bool = False
    italic: bool = False
    color: str | None = None
    size: float | None = None
    link: str | None = None


@dataclass
class Para:
    """A paragraph with a line budget (``max_lines``) used for truncation."""

    runs: list[Run]
    size: float = 12.0
    color: str = SLATE[700]
    bold: bool = False
    bullet: str | None = None
    bullet_color: str | None = None
    align: str = "l"
    space_after: float = 4.0
    max_lines: int = 3
    keep_with_next: bool = False
    serif: bool = False  # Georgia (titles, big figures) instead of Arial
    tracking: int = 0  # letter spacing in 1/100 pt (small upper-case labels)
    italic: bool = False

    @property
    def text(self) -> str:
        return "".join(r.text for r in self.runs)

    @property
    def max_size(self) -> float:
        return max([self.size, *(r.size for r in self.runs if r.size)])


def para(text: object, **kwargs: Any) -> Para:
    """Single-run paragraph."""
    return Para([Run(one_line(text))], **kwargs)


def heading(text: str, color: str = TEAL_DARK, size: float = 10) -> Para:
    """Small upper-case section label that stays with the paragraph after it."""
    return para(text.upper(), size=size, bold=True, color=color, max_lines=1, space_after=4, keep_with_next=True,
                tracking=80)


def _cpl(width_in: float, size: float, bold: bool = False) -> int:
    """Characters per line for a box width and font size."""
    return max(4, int(max(0.1, width_in) * 72 * 0.96 / (size * (BOLD_CHAR_W if bold else CHAR_W))))


def _line_h(size: float) -> float:
    return size * LINE_H / 72


def _truncate_runs(runs: list[Run], budget: int) -> list[Run]:
    out: list[Run] = []
    used = 0
    for run in runs:
        room = budget - used
        if len(run.text) <= room:
            out.append(run)
            used += len(run.text)
            continue
        if room > 3:
            lead = " " if run.text.startswith(" ") else ""
            whole = _sentence_cut(run.text.lstrip(), room - len(lead))  # prefer whole sentences over "…"
            out.append(replace(run, text=lead + (whole or clip(run.text, room - len(lead)))))
        elif out:
            out[-1] = replace(out[-1], text=out[-1].text.rstrip(" ·,;:—-") + "…")
        break
    return out or [Run("…")]


def _sentence_cut(text: str, limit: int) -> str:
    """The longest whole-sentence prefix that fits in ``limit`` characters (if it keeps at least ~half), else ""."""
    head = text[:limit]
    ends = [m.end() for m in re.finditer(r"[.!?](?=\s|$)", head)]
    return head[: ends[-1]] if ends and ends[-1] >= limit * 0.45 else ""


def _budget(text: str, cpl: int, limit: int) -> int:
    """Largest character count whose clipped text still wraps into ``limit`` lines."""
    budget = cpl * limit
    while budget > 1:
        if len(wrap_lines(clip(text, budget), cpl)) <= limit:
            return budget
        budget -= max(1, budget // 25)
    return 1


def _fit_para(p: Para, width_in: float, max_lines: int | None = None) -> tuple[Para, int]:
    """Clip a paragraph to its line budget; return it with its estimated line count."""
    limit = max(1, max_lines if max_lines is not None else p.max_lines)
    text_w = width_in - (BULLET_INDENT if p.bullet else 0.0)
    bold = p.serif or p.bold or all(r.bold for r in p.runs if r.text.strip())
    cpl = _cpl(text_w, p.max_size, bold)
    if p.tracking:  # letter spacing widens every glyph by tracking/100 pt
        glyph = p.max_size * (BOLD_CHAR_W if bold else CHAR_W)
        cpl = max(4, int(cpl * glyph / (glyph + p.tracking / 100)))
    lines = wrap_lines(p.text, cpl)
    if len(lines) <= limit:
        return p, max(1, len(lines))
    return replace(p, runs=_truncate_runs(p.runs, _budget(p.text, cpl, limit))), limit


def fit_paras(paras: Sequence[Para], width_in: float, height_in: float) -> tuple[list[Para], list[Para]]:
    """Paragraphs that fit the inner box (each clipped to its budget) and the overflow."""
    fitted: list[Para] = []
    used = 0.0
    for index, p in enumerate(paras):
        clipped, lines = _fit_para(p, width_in)
        height = lines * _line_h(p.max_size)
        if used + height > height_in + 1e-6:
            if not fitted:
                room = max(1, int(height_in / _line_h(p.max_size) + 1e-6))
                return [_fit_para(p, width_in, room)[0]], list(paras[index + 1 :])
            while fitted and fitted[-1].keep_with_next:
                fitted.pop()
                index -= 1
            return fitted, list(paras[index:])
        fitted.append(clipped)
        used += height + p.space_after / 72
    while len(fitted) > 1 and fitted[-1].keep_with_next:
        fitted.pop()
    return fitted, []


def paras_height(paras: Sequence[Para], width_in: float) -> float:
    """Estimated height (inches, including box padding) of fitted paragraphs."""
    total = 2 * PAD_Y
    for index, p in enumerate(paras):
        _, lines = _fit_para(p, width_in - 2 * PAD_X)
        total += lines * _line_h(p.max_size) + (p.space_after / 72 if index < len(paras) - 1 else 0)
    return total


def _bullet(paragraph: Any, char: str, color: str) -> None:
    p_pr = paragraph._p.get_or_add_pPr()
    indent = int(Inches(BULLET_INDENT))
    p_pr.set("marL", str(indent))
    p_pr.set("indent", str(-indent))
    bu_clr = OxmlElement("a:buClr")
    srgb = OxmlElement("a:srgbClr")
    srgb.set("val", color.lstrip("#").upper())
    bu_clr.append(srgb)
    bu_sz = OxmlElement("a:buSzPct")
    bu_sz.set("val", "100000")
    bu_font = OxmlElement("a:buFont")
    bu_font.set("typeface", "Arial")
    bu_char = OxmlElement("a:buChar")
    bu_char.set("char", char)
    for element in (bu_clr, bu_sz, bu_font, bu_char):
        p_pr.insert_element_before(element, "a:tabLst", "a:defRPr", "a:extLst")


def _write(text_frame: Any, paras: Sequence[Para]) -> None:
    for index, p in enumerate(paras):
        paragraph = text_frame.paragraphs[0] if index == 0 else text_frame.add_paragraph()
        paragraph.alignment = _ALIGN[p.align]
        paragraph.space_before = Pt(0)
        paragraph.space_after = Pt(p.space_after)
        paragraph.font.size = Pt(p.size)
        if p.bullet:
            _bullet(paragraph, p.bullet, p.bullet_color or p.color)
        for r in p.runs:
            run = paragraph.add_run()
            run.text = flatten(strip_codes(r.text))
            font = run.font
            font.name = SERIF if p.serif else FONT
            font.size = Pt(r.size or p.size)
            font.bold = r.bold or p.bold
            font.italic = r.italic or p.italic
            if p.tracking:
                run._r.get_or_add_rPr().set("spc", str(p.tracking))
            font.color.rgb = _rgb(r.color or p.color)
            link = safe_url(r.link) if r.link else None
            if link:  # http(s) only: never javascript:, data:, file: ...
                run.hyperlink.address = link
        paragraph._p.get_or_add_endParaRPr().set("sz", str(int(p.size * 100)))


