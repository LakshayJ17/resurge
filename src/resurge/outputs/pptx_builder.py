    def executive_summary(self) -> None:
        es = self.r.executive_summary
        slide = self.new("Executive summary", "Summary")
        self.toc.append(("Summary", "The headline, key findings, the numbers that matter, threats and opportunities",
                         len(self.prs.slides)))
        y = TOP
        if es.headline:
            self.text(slide, MARGIN, y, CONTENT_W, 0.84,
                      [para(es.headline, size=21, serif=True, color=INK, max_lines=2, space_after=0)])
            y += 0.86
        if es.summary:
            self.text(slide, MARGIN, y, CONTENT_W, 0.74,
                      [para(es.summary, size=12, color=SLATE[600], max_lines=3, space_after=0)])
            y += 0.78
        findings = list(es.key_findings)
        side = bool(es.top_threats or es.top_opportunities)
        if not (es.headline or es.summary or findings or side):
            self.text(slide, MARGIN, y, CONTENT_W, 0.5,
                      [para("No executive summary was produced for this run.", size=14, color=SLATE[500])])
            return
        y += 0.08
        list_w = 7.65 if side else CONTENT_W
        rest: list[Insight] = []
        if findings:
            self.text(slide, MARGIN, y, list_w, 0.3, [heading("Key findings")])
            rest = self.findings(slide, findings, MARGIN, y + 0.34, list_w, BOTTOM)
        if side:
            x = MARGIN + list_w + 0.35
            w = CONTENT_W - list_w - 0.35
            blocks = [(t, c, i) for t, c, i in (
                ("Top threats", RED, es.top_threats),
                ("Top opportunities", GREEN_DARK, es.top_opportunities),
            ) if i]
            h = (BOTTOM - y - GUTTER * (len(blocks) - 1)) / len(blocks)
            for k, (title, accent, items) in enumerate(blocks):
                self.card(slide, x, y + k * (h + GUTTER), w, h, title, accent,
                          self.bullet_paras(items, size=11, bullet_color=accent))
        self.notes(slide, (fid for f in findings for fid in f.fact_ids))
        while rest:
            slide = self.new("Executive summary (cont.)", "Summary")
            done = len(rest)
            rest = self.findings(slide, rest, MARGIN, TOP, CONTENT_W, BOTTOM)
            self.notes(slide, (fid for f in findings for fid in f.fact_ids))
            if len(rest) == done:  # nothing fitted: avoid an endless loop
                break

    def findings(self, slide: Slide, items: Sequence[Insight], x: float, y: float, w: float,
                 bottom: float) -> list[Insight]:
        """Key-finding rows (confidence badge + text); returns findings that did not fit."""
        text_w = w - 0.95
        for k, item in enumerate(items):
            p, lines = _fit_para(para(item.text, size=12.5, color=SLATE[800], max_lines=3, space_after=0),
                                 text_w - 2 * PAD_X)
            text_h = lines * _line_h(12.5) + 2 * PAD_Y
            row_h = max(text_h, 0.66)
            if y + row_h > bottom + 1e-6:
                return list(items[k:])
            fill, ink, label = _conf_style(insight_confidence(item, self.facts))
            self.badge(slide, x, y + 0.03, 0.8, 0.38, label, fill, ink, size=11.5)
            self.text(slide, x - 0.05, y + 0.42, 0.9, 0.24,
                      [para("inferred" if item.inferred else "confidence", size=8, color=SLATE[500], align="c",
                            max_lines=1, space_after=0)])
            self.text(slide, x + 0.95, y, text_w, text_h, [p])
            y += row_h + 0.12
        return []

    def landscape(self) -> None:
        listed = {c.name.casefold(): c for c in self.r.competitors}
        rows: list[list[TCell | str]] = []
        for name in competitor_names(self.r):
            profile = self.r.profile(name)
            comp = listed.get(name.casefold())
            if profile is None and comp is None:
                continue
            category = (profile.category if profile and profile.category else None) or (comp.category if comp else "")
            summary = (profile.summary if profile and profile.summary else None) or (
                comp.description if comp and comp.description else ""
            )
            level = profile.threat_level if profile else None
            threat = (
                TCell(f"{clamp_int(level, 1, 5)}/5 · {threat_label(level)}", bold=True, align="c",
                      fill=THREAT_FILL[clamp_int(level, 1, 5)])
                if level is not None
                else TCell("Unrated", color=SLATE[400], align="c")
            )
            rows.append([TCell(name, bold=True, swatch=self.color(name)), TCell(one_line(category).title() or "—"),
                         TCell(summary or "—"), threat])
        if not rows:
            return
        style = TableStyle(["Competitor", "Category", "What they are", "Threat"], [2.75, 1.3, 6.48, 1.8], size=11,
                           max_lines=2)
        pages = _paginate(rows, style, CONTENT_H)
        for k, page in enumerate(pages):
            slide = self.new("Competitive landscape (cont.)" if k else self.threat_title(), "Competitive landscape")
            rationale = [f"{p.name} - threat {clamp_int(p.threat_level, 1, 5)}/5: {p.threat_rationale}"
                         for p in self.r.profiles if p.threat_level is not None and p.threat_rationale]
            if rationale and k == 0:
                self.notes(slide, (), intro="Threat rationale: " + " • ".join(rationale))
            used = _draw_table(slide, MARGIN, TOP, style, page)
            room = CONTENT_H - used - 0.35
            if len(pages) == 1 and room >= 2.4 and "threat_levels" in self.charts:
                self.picture(slide, "threat_levels", MARGIN, TOP + used + 0.35, CONTENT_W, room)
                self.threat_shown = True

    def threat_title(self) -> str:
        rated = [p for p in self.r.profiles if p.threat_level is not None and p.name.casefold() != self.target.casefold()]
        if not rated:
            return "Competitive landscape"
        level = max(clamp_int(p.threat_level, 1, 5) for p in rated)
        top = [p.name for p in rated if clamp_int(p.threat_level, 1, 5) == level]
        if len(top) == 1:
            return f"{self.name(top[0])} is the biggest threat to {self.target}"
        if len(top) == 2:
            return f"{self.name(top[0])} and {self.name(top[1])} are the biggest threats"
        return f"{len(top)} competitors share the top threat level ({level} of 5)"

    def threat_assessment(self) -> None:
        profiles = sorted((p for p in self.r.profiles if p.threat_level is not None),
                          key=lambda p: -clamp_int(p.threat_level, 1, 5))
        if "threat_levels" not in self.charts or not profiles or self.threat_shown:
            return
        slide = self.new("Threat assessment", "Market map")
        placed = self.picture(slide, "threat_levels", MARGIN, TOP, 7.4, CONTENT_H, align="l")
        x = MARGIN + (placed[2] if placed else 7.4) + 0.35
        paras: list[Para] = []
        fact_ids: list[str] = []
        for p in profiles:
            level = clamp_int(p.threat_level, 1, 5)
            paras.append(Para([Run(f"{one_line(p.name)}  ", bold=True, color=SLATE[900]),
                               Run(f"{level}/5 · {threat_label(level)}", color=SLATE[500])],
                              size=11.5, max_lines=1, space_after=1, keep_with_next=True))
            move = p.recent_moves[0] if p.recent_moves else None
            detail = move.text if move else (p.summary or "")
            if move:
                fact_ids += move.fact_ids
            if detail:
                paras.append(para(detail, size=10.5, color=SLATE[600], max_lines=3, space_after=10))
        self.text(slide, x, TOP, SLIDE_W - MARGIN - x, CONTENT_H, [heading("Why it matters"), *paras])
        self.notes(slide, fact_ids)

