    def pricing_takeaways(self) -> list[str]:
        """Deterministic one-liners: cheapest entry, top list price, free and unpublished tiers."""
        priced = [p for p in self.r.profiles if p.pricing]
        paid = [(p.name, t) for p in priced for t in p.pricing if t.price_monthly_usd and t.price_monthly_usd > 0]
        out: list[str] = []
        if paid:
            low = min(paid, key=lambda item: item[1].price_monthly_usd or 0)
            high = max(paid, key=lambda item: item[1].price_monthly_usd or 0)
            out.append(f"Lowest paid entry: {low[0]} {low[1].name} at {fmt_usd(low[1].price_monthly_usd)} / month")
            out.append(f"Highest listed price: {high[0]} {high[1].name} at "
                       f"{fmt_usd(high[1].price_monthly_usd)} / month")
        free = [p.name for p in priced if any(t.price_monthly_usd is not None and t.price_monthly_usd <= 0
                                               for t in p.pricing)]
        if priced:
            out.append(f"Free plan: {len(free)} of {len(priced)} competitors"
                       + (f" ({join(free, ', ')})" if free else ""))
        custom = [p.name for p in priced if any(t.price_monthly_usd is None for t in p.pricing)]
        if custom:
            out.append(f"Unpublished (contact-sales) tiers: {join(custom, ', ')}")
        return out

