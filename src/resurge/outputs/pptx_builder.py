"""PowerPoint deck builder (python-pptx, 16:9, 13.333 x 7.5 in).

Every slide is drawn on the blank layout with explicit geometry: a navy title
bar, a content area and a footer (report title, date, page number, Resurge
attribution). Nothing relies on PowerPoint autofit: each text block is fitted
to a character budget derived from its box and font size, truncated with "…",
and long lists or tables continue on "(cont.)" slides. Slides that use facts
carry their citations (fact IDs, claims, source URLs) in the speaker notes.
Hyperlinks and cited URLs are http(s) only (``safe_url``), since all report
text comes from untrusted sources.
"""

